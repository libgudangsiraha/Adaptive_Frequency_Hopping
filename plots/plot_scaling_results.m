function plot_scaling_results(scalingTable, outputFile)
%PLOT_SCALING_RESULTS Goodput and runtime versus K and T.

    learners = unique(scalingTable.Learner, 'stable');

    figure('Visible', 'off');
    tiledlayout(2, 2);

    nexttile;
    plot_subset(scalingTable, learners, "K", ...
        "GoodputMbps", ...
        "Number of channels K", ...
        "Goodput (Mbps)", ...
        "Goodput scaling with K");

    nexttile;
    plot_subset(scalingTable, learners, "K", ...
        "RuntimeSeconds", ...
        "Number of channels K", ...
        "Runtime (s)", ...
        "Runtime scaling with K");

    nexttile;
    plot_subset(scalingTable, learners, "T", ...
        "FixedArmRegret", ...
        "Horizon T", ...
        "Fixed-arm regret", ...
        "Regret scaling with T");

    nexttile;
    plot_subset(scalingTable, learners, "T", ...
        "RuntimeSeconds", ...
        "Horizon T", ...
        "Runtime (s)", ...
        "Runtime scaling with T");

    saveas(gcf, outputFile);
    close(gcf);

end


function plot_subset(inputTable, learners, scaleType, ...
    valueField, xLabelText, yLabelText, titleText)

    hold on;

    for index = 1:numel(learners)
        mask = ...
            inputTable.Learner == learners(index) ...
            & inputTable.ScaleType == scaleType;

        subset = sortrows(inputTable(mask, :), 'ScaleValue');

        plot( ...
            subset.ScaleValue, ...
            subset.(char(valueField)), ...
            '-o', ...
            'DisplayName', learners(index));
    end

    xlabel(xLabelText);
    ylabel(yLabelText);
    title(titleText);
    grid on;
    legend('Location', 'best');
    hold off;

end

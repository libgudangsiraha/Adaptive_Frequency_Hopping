function outputs = run_model_mismatch_preflight(mode)
%RUN_MODEL_MISMATCH_PREFLIGHT Fast fail-before-bandit gate.
%
% This routine is deliberately cheap. It verifies that the environment
% actually creates held-out representational headroom for the Local
% model class before the online probe is launched.

    if nargin < 1
        mode = "quick";
    end

    projectRoot = setup_paths();
    mode = lower(string(mode));

    switch mode
        case "smoke"
            T = 500;
            seedList = 99501:99502;
            minimumGain = 0.000;

        case "quick"
            T = 3000;
            seedList = 99501:99505;
            minimumGain = 0.005;

        case "full"
            T = 8000;
            seedList = 99501:99510;
            minimumGain = 0.005;

        otherwise
            error("Unknown preflight mode: %s", mode);
    end

    regimes = [ ...
        "nonlinear_interaction"; ...
        "observable_switching"];

    regimeLabels = [ ...
        "Nonlinear interaction"; ...
        "Observable switching"];

    rows = cell(numel(regimes), 1);

    for regimeIndex = 1:numel(regimes)

        seedRows = cell(numel(seedList), 1);

        for seedIndex = 1:numel(seedList)

            cfg = get_base_config();
            cfg.T = T;
            cfg.seed = seedList(seedIndex);
            cfg.environment_regime = regimes(regimeIndex);
            cfg.M_jam = 1;
            cfg.occ_prob = 0.10;
            cfg.model_mismatch_min_capture_gain = minimumGain;

            rng(cfg.seed, "twister");

            result = evaluate_model_mismatch_oracle(cfg);

            seedRows{seedIndex} = table( ...
                cfg.seed, ...
                result.globalCapture, ...
                result.localCapture, ...
                result.captureGain, ...
                result.globalGoodputMbps, ...
                result.localGoodputMbps, ...
                result.goodputGainMbps, ...
                result.globalTopAccuracy, ...
                result.localTopAccuracy, ...
                'VariableNames', { ...
                    'Seed', ...
                    'GlobalCapture', ...
                    'LocalCapture', ...
                    'CaptureGain', ...
                    'GlobalGoodputMbps', ...
                    'LocalGoodputMbps', ...
                    'GoodputGainMbps', ...
                    'GlobalTopAccuracy', ...
                    'LocalTopAccuracy'});
        end

        seedTable = vertcat(seedRows{:});

        [captureGain, captureGainCI] = ...
            mean_ci(seedTable.CaptureGain);

        [goodputGain, goodputGainCI] = ...
            mean_ci(seedTable.GoodputGainMbps);

        pass = ...
            captureGain - captureGainCI >= minimumGain;

        rows{regimeIndex} = table( ...
            regimeLabels(regimeIndex), ...
            mean(seedTable.GlobalCapture), ...
            mean(seedTable.LocalCapture), ...
            captureGain, ...
            captureGainCI, ...
            mean(seedTable.GlobalGoodputMbps), ...
            mean(seedTable.LocalGoodputMbps), ...
            goodputGain, ...
            goodputGainCI, ...
            mean(seedTable.GlobalTopAccuracy), ...
            mean(seedTable.LocalTopAccuracy), ...
            minimumGain, ...
            pass, ...
            'VariableNames', { ...
                'Regime', ...
                'GlobalCapture', ...
                'LocalCapture', ...
                'LocalMinusGlobalCapture', ...
                'LocalMinusGlobalCaptureCI95', ...
                'GlobalGoodputMbps', ...
                'LocalGoodputMbps', ...
                'LocalMinusGlobalGoodputMbps', ...
                'LocalMinusGlobalGoodputCI95', ...
                'GlobalTopAccuracy', ...
                'LocalTopAccuracy', ...
                'RequiredCaptureGain', ...
                'Pass'});
    end

    tableP = vertcat(rows{:});

    outputRoot = fullfile( ...
        projectRoot, ...
        "results", ...
        "model_mismatch_preflight", ...
        char(mode));

    tableFolder = fullfile(outputRoot, "tables");

    if ~isfolder(tableFolder)
        mkdir(tableFolder);
    end

    write_table_bundle(tableP, fullfile( ...
        tableFolder, ...
        "Table_PF_model_mismatch_preflight"));

    fprintf("\n========================================\n");
    fprintf("Model-mismatch preflight: %s\n", upper(mode));
    fprintf("========================================\n");
    disp(tableP);

    if all(tableP.Pass)
        fprintf("PREFLIGHT PASS: launch the online model-class probe.\n");
    else
        fprintf([ ...
            "PREFLIGHT FAIL: do not spend time on the online probe. " ...
            "Inspect the failed regime first.\n"]);
    end

    outputs.outputRoot = outputRoot;
    outputs.tableP = tableP;
    outputs.allPass = all(tableP.Pass);

end


function [meanValue, ci95] = mean_ci(values)

    values = values(:);
    values = values(isfinite(values));

    meanValue = mean(values);

    if numel(values) <= 1
        ci95 = NaN;
    else
        ci95 = 1.96 * std(values) / sqrt(numel(values));
    end

end

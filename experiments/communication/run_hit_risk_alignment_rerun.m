function outputs = run_hit_risk_alignment_rerun(mode)
%RUN_HIT_RISK_ALIGNMENT_RERUN Four-way calibrated-risk comparison.
%
% Variants:
%   1. LC-Tsallis-INF-Online
%   2. D-PACT-AFH-Base
%   3. D-PACT-AFH with legacy q-overlap risk
%   4. D-PACT-AFH with exact attack-set hit risk
%
% Examples:
%   run_hit_risk_alignment_rerun("smoke")
%   run_hit_risk_alignment_rerun("quick")
%   run_hit_risk_alignment_rerun("full")

    if nargin < 1
        mode = "smoke";
    end

    projectRoot = setup_paths();
    suite = get_hit_risk_rerun_config(mode);

    outputRoot = fullfile(projectRoot, suite.outputRoot);
    tableFolder = fullfile(outputRoot, "tables");
    figureFolder = fullfile(outputRoot, "figures");
    rawFolder = fullfile(outputRoot, "raw");
    checkpointFolder = fullfile(outputRoot, "checkpoints");

    ensure_folder(tableFolder);
    ensure_folder(figureFolder);
    ensure_folder(rawFolder);
    ensure_folder(checkpointFolder);

    cfg = get_base_config();
    cfg.T = suite.T;
    cfg.seedList = suite.seedList;
    cfg.numSeeds = numel(suite.seedList);
    cfg.checkpoint_root = checkpointFolder;
    cfg.resume = true;
    cfg.use_parallel = true;
    cfg.store_full_histories = false;
    cfg.store_metric_timeseries = false;
    cfg.reward_mode = "outage_capped";

    variants = alignment_variants();
    rows = cell(numel(variants), 1);
    raw = cell(numel(variants), 1);

    fprintf("\n########################################\n");
    fprintf("Hit-risk alignment rerun: %s\n", mode);
    fprintf("T = %d, seeds = %d, M_jam = %d\n", ...
        cfg.T, numel(cfg.seedList), cfg.M_jam);
    fprintf("########################################\n");

    for variantIndex = 1:numel(variants)

        variant = variants(variantIndex);
        cfgRun = cfg;
        cfgRun.dynamic_prediction_risk_mode = ...
            variant.riskMode;

        fprintf("\n===== %s =====\n", variant.name);

        multi = run_multi_seed_pair( ...
            cfgRun, variant.learnerType, ...
            suite.adversaryType);

        rows{variantIndex} = alignment_summary_row( ...
            variant, multi);

        raw{variantIndex} = multi;
    end

    tableH1 = vertcat(rows{:});
    tableH2 = paired_effect_table(variants, raw);

    write_table_bundle(tableH1, fullfile( ...
        tableFolder, "Table_H1_hit_risk_alignment"));

    write_table_bundle(tableH2, fullfile( ...
        tableFolder, "Table_H2_paired_effects"));

    save(fullfile(rawFolder, "H1_hit_risk_alignment.mat"), ...
        "raw", "tableH1", "tableH2", ...
        "cfg", "suite", "variants", "-v7.3");

    plot_hit_risk_alignment(tableH1, fullfile( ...
        figureFolder, "Figure_H1_hit_risk_alignment.png"));

    reportPath = fullfile(outputRoot, "ALIGNMENT_VERDICT.md");
    write_hit_risk_verdict( ...
        reportPath, tableH1, tableH2, cfg);

    outputs.outputRoot = outputRoot;
    outputs.tableH1 = tableH1;
    outputs.tableH2 = tableH2;
    outputs.reportPath = reportPath;

    fprintf("\nHit-risk alignment rerun completed.\n");
    fprintf("Read: %s\n", reportPath);

end


function variants = alignment_variants()

    variants = repmat(struct( ...
        'name', "", ...
        'learnerType', "", ...
        'riskMode', ""), 4, 1);

    variants(1) = make_variant( ...
        "LC-Tsallis-INF-Online", ...
        "lc_inf_online", "q_overlap");

    variants(2) = make_variant( ...
        "D-PACT-AFH-Base", ...
        "dpact_nodetect", "hit_probability");

    variants(3) = make_variant( ...
        "D-PACT-AFH q-overlap", ...
        "dpact_detect", "q_overlap");

    variants(4) = make_variant( ...
        "D-PACT-AFH hit-risk", ...
        "dpact_detect", "hit_probability");

end


function variant = make_variant(name, learnerType, riskMode)

    variant.name = string(name);
    variant.learnerType = string(learnerType);
    variant.riskMode = string(riskMode);

end


function row = alignment_summary_row(variant, multi)

    s = multi.summary;

    row = table( ...
        variant.name, ...
        variant.learnerType, ...
        variant.riskMode, ...
        s.meanAvgReward, ...
        s.ci95AvgReward, ...
        s.meanGoodputMbps, ...
        s.ci95GoodputMbps, ...
        s.meanPdr, ...
        s.ci95Pdr, ...
        s.meanOverlap, ...
        s.ci95Overlap, ...
        s.meanExpectedJamHit, ...
        s.ci95ExpectedJamHit, ...
        s.meanJamHitRate, ...
        s.ci95JamHitRate, ...
        s.meanJamCalibrationGap, ...
        s.ci95JamCalibrationGap, ...
        s.meanMasterLcMass, ...
        s.meanMasterLocalMass, ...
        s.meanRuntime, ...
        'VariableNames', { ...
            'Variant', ...
            'LearnerType', ...
            'RiskMode', ...
            'Reward', ...
            'RewardCI95', ...
            'GoodputMbps', ...
            'GoodputCI95', ...
            'PDR', ...
            'PDRCI95', ...
            'Overlap', ...
            'OverlapCI95', ...
            'ExpectedJamHit', ...
            'ExpectedJamHitCI95', ...
            'EmpiricalJamHit', ...
            'EmpiricalJamHitCI95', ...
            'CalibrationGap', ...
            'CalibrationGapCI95', ...
            'MasterLcMass', ...
            'MasterLocalMass', ...
            'RuntimeSeconds'});

end


function output = paired_effect_table(variants, raw)

    comparisons = [ ...
        3, 2; ... % q-overlap Full minus Base
        4, 2; ... % hit-risk Full minus Base
        4, 3  ... % hit-risk Full minus q-overlap Full
    ];

    rows = cell(size(comparisons, 1), 1);

    for index = 1:size(comparisons, 1)

        treatmentIndex = comparisons(index, 1);
        referenceIndex = comparisons(index, 2);

        treatment = raw{treatmentIndex};
        reference = raw{referenceIndex};

        [goodputEffect, goodputCI] = mean_ci( ...
            treatment.avgGoodputMbps ...
            - reference.avgGoodputMbps);

        [expectedHitEffect, expectedHitCI] = mean_ci( ...
            treatment.expectedJamHit ...
            - reference.expectedJamHit);

        [empiricalHitEffect, empiricalHitCI] = mean_ci( ...
            treatment.jamHitRate ...
            - reference.jamHitRate);

        [overlapEffect, overlapCI] = mean_ci( ...
            treatment.avgOverlap ...
            - reference.avgOverlap);

        rows{index} = table( ...
            variants(treatmentIndex).name, ...
            variants(referenceIndex).name, ...
            goodputEffect, goodputCI, ...
            overlapEffect, overlapCI, ...
            expectedHitEffect, expectedHitCI, ...
            empiricalHitEffect, empiricalHitCI, ...
            'VariableNames', { ...
                'Treatment', ...
                'Reference', ...
                'GoodputEffect', ...
                'GoodputEffectCI95', ...
                'OverlapEffect', ...
                'OverlapEffectCI95', ...
                'ExpectedJamHitEffect', ...
                'ExpectedJamHitEffectCI95', ...
                'EmpiricalJamHitEffect', ...
                'EmpiricalJamHitEffectCI95'});
    end

    output = vertcat(rows{:});

end


function [meanValue, ci95] = mean_ci(values)

    values = values(:);
    values = values(isfinite(values));

    meanValue = mean(values);

    if numel(values) <= 1
        ci95 = NaN;
    else
        ci95 = 1.96 * std(values) / sqrt(numel(values));
    end

end


function ensure_folder(pathValue)

    if ~isfolder(pathValue)
        mkdir(pathValue);
    end

end

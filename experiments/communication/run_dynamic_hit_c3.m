        get_adversary_display_name(multi.adversaryType), ...
        pointLabel, ...
        beta, ...
        nu, ...
        s.meanAvgReward, ...
        s.ci95AvgReward, ...
        s.meanGoodputMbps, ...
        s.ci95GoodputMbps, ...
        s.meanPdr, ...
        s.ci95Pdr, ...
        s.meanMeanSinrDb, ...
        s.ci95MeanSinrDb, ...
        s.meanOverlap, ...
        s.ci95Overlap, ...
        s.meanExpectedJamHit, ...
        s.ci95ExpectedJamHit, ...
        s.meanJamHitRate, ...
        s.ci95JamHitRate, ...
        s.meanJamCalibrationGap, ...
        s.ci95JamCalibrationGap, ...
        s.meanSwitchingRate, ...
        s.ci95SwitchingRate, ...
        s.meanMasterLcMass, ...
        s.meanMasterLocalMass, ...
        s.meanRuntime, ...
        'VariableNames', { ...
            'Learner', ...
            'Adversary', ...
            'OperatingPoint', ...
            'Beta', ...
            'Nu', ...
            'Reward', ...
            'RewardCI95', ...
            'GoodputMbps', ...
            'GoodputCI95', ...
            'PDR', ...
            'PDRCI95', ...
            'MeanSINRdB', ...
            'MeanSINRdBCI95', ...
            'Overlap', ...
            'OverlapCI95', ...
            'ExpectedJamHit', ...
            'ExpectedJamHitCI95', ...
            'EmpiricalJamHit', ...
            'EmpiricalJamHitCI95', ...
            'CalibrationGap', ...
            'CalibrationGapCI95', ...
            'SwitchingRate', ...
            'SwitchingRateCI95', ...
            'MasterLcMass', ...
            'MasterLocalMass', ...
            'RuntimeSeconds'});

end


function tableEffects = c3_paired_effects( ...
    tableC3, raw, suite)

    comparisons = [ ...
        "D-PACT-AFH", "LC-Tsallis-INF-Online"; ...
        "D-PACT-AFH", "D-PACT-AFH-Base"; ...
        "D-PACT-AFH", "AUFH-EXP3++-1"];

    rows = cell( ...
        numel(suite.adversaries) ...
        * size(comparisons, 1), 1);

    rowIndex = 0;

    for adversaryIndex = 1:numel(suite.adversaries)

        adversaryName = get_adversary_display_name( ...
            suite.adversaries(adversaryIndex));

        for comparisonIndex = 1:size(comparisons, 1)

            treatmentName = comparisons(comparisonIndex, 1);
            referenceName = comparisons(comparisonIndex, 2);

            treatmentIndex = find( ...
                tableC3.Adversary == adversaryName ...
                & tableC3.Learner == treatmentName, ...
                1, "first");

            referenceIndex = find( ...
                tableC3.Adversary == adversaryName ...
                & tableC3.Learner == referenceName, ...
                1, "first");

            if isempty(treatmentIndex) || isempty(referenceIndex)
                error("Missing C3 comparison row.");
            end

            treatment = raw{treatmentIndex};
            reference = raw{referenceIndex};

            [goodputEffect, goodputCI] = mean_ci( ...
                treatment.avgGoodputMbps ...
                - reference.avgGoodputMbps);

            [pdrEffect, pdrCI] = mean_ci( ...
                treatment.pdr - reference.pdr);

            [hitEffect, hitCI] = mean_ci( ...
                treatment.jamHitRate ...
                - reference.jamHitRate);

            [overlapEffect, overlapCI] = mean_ci( ...
                treatment.avgOverlap ...
                - reference.avgOverlap);

            rowIndex = rowIndex + 1;

            rows{rowIndex} = table( ...
                adversaryName, ...
                treatmentName, ...
                referenceName, ...
                goodputEffect, ...
                goodputCI, ...
                pdrEffect, ...
                pdrCI, ...
                overlapEffect, ...
                overlapCI, ...
                hitEffect, ...
                hitCI, ...
                'VariableNames', { ...
                    'Adversary', ...
                    'Treatment', ...
                    'Reference', ...
                    'GoodputEffect', ...
                    'GoodputEffectCI95', ...
                    'PDREffect', ...
                    'PDREffectCI95', ...
                    'OverlapEffect', ...
                    'OverlapEffectCI95', ...
                    'EmpiricalJamHitEffect', ...
                    'EmpiricalJamHitEffectCI95'});
        end
    end

    tableEffects = vertcat(rows{:});

end


function [beta, nu, label, sourcePath] = ...
    resolve_operating_point( ...
        projectRoot, mode, requestedLabel, suite)

    requestedLabel = lower(string(requestedLabel));
    validLabels = ["throughput", "balanced", "low_risk"];

    if ~ismember(requestedLabel, validLabels)
        error( ...
            "Operating point must be throughput, balanced, or low_risk.");
    end

    candidateModes = unique([ ...
        string(mode), "full", "quick"], "stable");

    for candidateMode = candidateModes

        candidate = fullfile( ...
            projectRoot, ...
            "results", ...
            "dynamic_hit_pareto", ...
            char(candidateMode), ...
            "tables", ...
            "Table_P2_recommended_operating_points.csv");

        if ~isfile(candidate)
            continue;
        end

        pointTable = readtable(candidate, ...
            "TextType", "string");

        match = lower(pointTable.Label) == requestedLabel;

        if any(match)
            beta = pointTable.Beta(find(match, 1, "first"));
            nu = pointTable.Nu(find(match, 1, "first"));
            label = requestedLabel;
            sourcePath = string(candidate);
            return;
        end
    end

    beta = suite.defaultBeta;
    nu = suite.defaultNu;
    label = requestedLabel + "_fallback";
    sourcePath = "default beta=8, nu=1";

    warning( ...
        "No Pareto recommendation file was found. " ...
        + "Using beta=%g, nu=%g.", ...
        beta, nu);

end


function write_c3_summary( ...
    outputPath, tableC3, tableEffects, ...
    pointLabel, beta, nu, suite)

    fileId = fopen(outputPath, "w");

    if fileId < 0
        warning("Could not create C3 summary.");
        return;
    end

    cleanup = onCleanup(@() fclose(fileId));

    fprintf(fileId, "# Dynamic hit-risk C3\n\n");
    fprintf(fileId, "- Operating point: `%s`\n", pointLabel);
    fprintf(fileId, "- beta: %.6g\n", beta);
    fprintf(fileId, "- nu: %.6g\n", nu);
    fprintf(fileId, "- Horizon: %d\n", suite.T);
    fprintf(fileId, "- Seeds: %d\n", numel(suite.seedList));
    fprintf(fileId, "- Common attack budget: %d channel\n\n", ...
        suite.attackBudget);

    adversaries = unique(tableC3.Adversary, "stable");

    for index = 1:numel(adversaries)

        adversary = adversaries(index);
        subset = tableC3(tableC3.Adversary == adversary, :);

        [~, bestGoodputIndex] = max(subset.GoodputMbps);
        [~, lowestRiskIndex] = min(subset.EmpiricalJamHit);

        fprintf(fileId, "## %s\n\n", adversary);
        fprintf(fileId, "- Highest goodput: %s (%.6f Mbps)\n", ...
            subset.Learner(bestGoodputIndex), ...
            subset.GoodputMbps(bestGoodputIndex));
        fprintf(fileId, "- Lowest empirical jam-hit: %s (%.6f)\n\n", ...
            subset.Learner(lowestRiskIndex), ...
            subset.EmpiricalJamHit(lowestRiskIndex));
    end

    fprintf(fileId, ...
        "Paired comparisons are reported in " ...
        "`Table_C3_paired_effects.csv`.\n");

end


function [meanValue, ci95] = mean_ci(values)

    values = values(:);
    values = values(isfinite(values));

    if isempty(values)
        meanValue = NaN;
        ci95 = NaN;
        return;
    end

    meanValue = mean(values);

    if numel(values) <= 1
        ci95 = NaN;
    else
        ci95 = 1.96 * std(values) / sqrt(numel(values));
    end

end


function ensure_folder(pathValue)

    if ~isfolder(pathValue)
        mkdir(pathValue);
    end

end

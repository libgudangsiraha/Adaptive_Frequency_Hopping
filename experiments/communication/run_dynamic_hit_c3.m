function outputs = run_dynamic_hit_c3(mode, operatingPoint)
%RUN_DYNAMIC_HIT_C3 Final external-attacker robustness experiment.
%
% Examples:
%   run_dynamic_hit_c3("smoke", "balanced")
%   run_dynamic_hit_c3("quick", "balanced")
%   run_dynamic_hit_c3("full", "balanced")
%   run_dynamic_hit_c3("full", "throughput")
%   run_dynamic_hit_c3("full", "low_risk")
%
% The selected operating point is loaded from:
%   results/dynamic_hit_pareto/<mode>/tables/
%       Table_P2_recommended_operating_points.csv
%
% If the file is unavailable, the runner falls back to beta=8, nu=1.

    if nargin < 1
        mode = "quick";
    end

    if nargin < 2
        operatingPoint = "balanced";
    end

    projectRoot = setup_paths();
    suite = get_dynamic_hit_c3_config(mode);

    [selectedBeta, selectedNu, selectedLabel, sourcePath] = ...
        resolve_operating_point( ...
            projectRoot, mode, operatingPoint, suite);

    outputRoot = fullfile(projectRoot, suite.outputRoot);
    tableFolder = fullfile(outputRoot, "tables");
    figureFolder = fullfile(outputRoot, "figures");
    rawFolder = fullfile(outputRoot, "raw");
    checkpointFolder = fullfile(outputRoot, "checkpoints");

    ensure_folder(tableFolder);
    ensure_folder(figureFolder);
    ensure_folder(rawFolder);
    ensure_folder(checkpointFolder);

    cfgBase = get_base_config();
    cfgBase.T = suite.T;
    cfgBase.seedList = suite.seedList;
    cfgBase.numSeeds = numel(suite.seedList);

    cfgBase.M_jam = suite.attackBudget;
    cfgBase.sweep_width = suite.attackBudget;
    cfgBase.folpetti_mc_samples = suite.folpettiMcSamples;

    cfgBase.environment_regime = "stochastic";
    cfgBase.reward_mode = "outage_capped";
    cfgBase.dynamic_prediction_risk_mode = "hit_probability";

    cfgBase.detect_beta = selectedBeta;
    cfgBase.explore_nu = selectedNu;

    cfgBase.resume = true;
    cfgBase.use_parallel = true;
    cfgBase.parallel_workers = 0;
    cfgBase.checkpoint_root = checkpointFolder;
    cfgBase.store_full_histories = false;
    cfgBase.store_metric_timeseries = false;

    numRuns = ...
        numel(suite.adversaries) ...
        * numel(suite.learners);

    rows = cell(numRuns, 1);
    raw = cell(numRuns, 1);
    rowIndex = 0;

    fprintf("\n########################################\n");
    fprintf("Dynamic hit-risk C3: %s\n", mode);
    fprintf("T = %d | seeds = %d | common attack budget = %d\n", ...
        cfgBase.T, numel(cfgBase.seedList), cfgBase.M_jam);
    fprintf("Operating point: %s | beta=%g | nu=%g\n", ...
        selectedLabel, selectedBeta, selectedNu);
    fprintf("Point source: %s\n", sourcePath);
    fprintf("########################################\n");

    for adversaryIndex = 1:numel(suite.adversaries)

        adversary = suite.adversaries(adversaryIndex);

        for learnerIndex = 1:numel(suite.learners)

            rowIndex = rowIndex + 1;
            learner = suite.learners(learnerIndex);

            fprintf("\n===== %s | %s =====\n", ...
                get_adversary_display_name(adversary), ...
                get_learner_display_name(learner));

            multi = run_multi_seed_pair( ...
                cfgBase, learner, adversary);

            raw{rowIndex} = multi;
            rows{rowIndex} = c3_summary_row( ...
                multi, selectedLabel, ...
                selectedBeta, selectedNu);

            partial = vertcat(rows{1:rowIndex});
            writetable(partial, fullfile( ...
                tableFolder, "Table_C3_partial.csv"));

            save(fullfile(rawFolder, "C3_partial.mat"), ...
                "raw", "rows", "cfgBase", "suite", ...
                "selectedBeta", "selectedNu", ...
                "selectedLabel", "-v7.3");
        end
    end

    tableC3 = vertcat(rows{:});
    tableEffects = c3_paired_effects( ...
        tableC3, raw, suite);

    write_table_bundle(tableC3, fullfile( ...
        tableFolder, "Table_C3_external_attackers"));

    write_table_bundle(tableEffects, fullfile( ...
        tableFolder, "Table_C3_paired_effects"));

    save(fullfile(rawFolder, "C3_dynamic_hit.mat"), ...
        "raw", "tableC3", "tableEffects", ...
        "cfgBase", "suite", "selectedBeta", ...
        "selectedNu", "selectedLabel", "-v7.3");

    plot_dynamic_hit_c3_heatmaps( ...
        tableC3, fullfile(figureFolder, ...
            "Figure_C3_external_attacker_heatmaps.png"));

    plot_dynamic_hit_c3_pareto( ...
        tableC3, fullfile(figureFolder, ...
            "Figure_C3_external_attacker_pareto.png"));

    reportPath = fullfile(outputRoot, "C3_SUMMARY.md");
    write_c3_summary( ...
        reportPath, tableC3, tableEffects, ...
        selectedLabel, selectedBeta, selectedNu, suite);

    outputs.outputRoot = outputRoot;
    outputs.tableC3 = tableC3;
    outputs.tableEffects = tableEffects;
    outputs.operatingPoint = table( ...
        selectedLabel, selectedBeta, selectedNu, ...
        'VariableNames', {'Label', 'Beta', 'Nu'});
    outputs.reportPath = reportPath;

    fprintf("\nDynamic hit-risk C3 completed.\n");
    fprintf("Read: %s\n", reportPath);

end



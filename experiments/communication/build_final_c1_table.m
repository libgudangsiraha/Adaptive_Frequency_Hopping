        "Spectrum action space"; ...
        "Rounds per full experiment"; ...
        "Common attack budget"; ...
        "Normalized physical model"; ...
        "Normalized physical model"; ...
        "Exogenous occupancy"; ...
        "Normalized jammer power"; ...
        "Goodput readout"; ...
        "Packet delivery model"; ...
        "Packet delivery model"; ...
        "Successful-delivery gate"; ...
        "Finite-rate readout"; ...
        "Public context"; ...
        "Calibrated hit-risk master loss"; ...
        "Directional policy tilt (disabled)"; ...
        "Piecewise local-linear base"; ...
        "Piecewise local-linear base"; ...
        "Reference-calibrated safety point"];

    tableC1 = table(parameter, value, role, ...
        'VariableNames', {'Parameter', 'Value', 'Role'});

end

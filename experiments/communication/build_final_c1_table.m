%BUILD_FINAL_C1_TABLE Final system and algorithm parameter table.

    if nargin < 1
        mode = "full";
    end

    cfg = get_base_config();
    suite = get_final_c1_c4_config(mode);

    parameter = [ ...
        "Number of channels K"; ...
        "Horizon T"; ...
        "Attacked channels M"; ...
        "Transmit power"; ...
        "Noise floor"; ...
        "Natural occupancy probability"; ...
        "Jammer strength"; ...
        "Bandwidth"; ...
        "Packet size"; ...
        "Slot duration"; ...
        "Outage threshold"; ...
        "MCS spectral-efficiency cap"; ...
        "Context dimension"; ...
        "D-PACT risk coefficient beta"; ...
        "D-PACT tilt coefficient nu"; ...
        "Local partition bins"; ...
        "Local ridge coefficient"; ...
        "Safe operating-point label"];

    value = [ ...
        string(cfg.K); ...
        string(suite.T); ...
        string(suite.attackBudget); ...
        string(cfg.P_tx); ...
        string(cfg.noise_floor); ...
        string(cfg.occ_prob); ...
        string(cfg.jam_strength); ...
        sprintf("%.0f Hz", cfg.bandwidth_Hz); ...
        sprintf("%.0f bits", cfg.packet_bits); ...
        sprintf("%.4g s", cfg.slot_duration_s); ...
        sprintf("%.2f dB", cfg.sinr_outage_threshold_dB); ...
        sprintf("%.2f bit/s/Hz", cfg.mcs_cap_bps_hz); ...
        string(cfg.contextDim); ...
        string(suite.beta); ...
        string(suite.nu); ...
        mat2str(cfg.local_linear_bins); ...
        string(cfg.local_linear_ridge); ...
        suite.safeLabel];


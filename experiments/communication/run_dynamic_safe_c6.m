function outputs = run_dynamic_safe_c6(mode)
%RUN_DYNAMIC_SAFE_C6 Channel-count and horizon scaling.

    if nargin < 1
        mode = "quick";
    end

    projectRoot = setup_paths();
    suite = get_dynamic_c5_c6_config(mode);
    safePoint = resolve_dynamic_safe_operating_point( ...
        projectRoot, suite.safeLabel);

    outputRoot = fullfile(projectRoot, suite.c6OutputRoot);
    tableFolder = fullfile(outputRoot, "tables");
    figureFolder = fullfile(outputRoot, "figures");
    rawFolder = fullfile(outputRoot, "raw");
    checkpointFolder = fullfile(outputRoot, "checkpoints");

    ensure_folder(tableFolder);
    ensure_folder(figureFolder);
    ensure_folder(rawFolder);
    ensure_folder(checkpointFolder);

    cfgBase = get_base_config();
    cfgBase.seedList = suite.c6Seeds;
    cfgBase.numSeeds = numel(suite.c6Seeds);

    cfgBase.M_jam = suite.attackBudget;
    cfgBase.sweep_width = suite.attackBudget;
    cfgBase.detect_beta = suite.beta;
    cfgBase.explore_nu = suite.nu;
    cfgBase.dynamic_prediction_risk_mode = ...
        "hit_probability";
    cfgBase.environment_regime = "stochastic";

    cfgBase.resume = true;
    cfgBase.use_parallel = true;
    cfgBase.parallel_workers = 0;
    cfgBase.checkpoint_root = checkpointFolder;
    cfgBase.store_full_histories = false;
    cfgBase.store_metric_timeseries = false;

    numRows = ...
        (numel(suite.c6KGrid) + numel(suite.c6TGrid)) ...
        * numel(suite.learners);

    rows = cell(numRows, 1);
    raw = cell(numRows, 1);
    rowIndex = 0;

    %% K scaling
    for K = suite.c6KGrid

        cfg = cfgBase;
        cfg.K = K;
        cfg.T = suite.c6KScalingT;
        cfg.fc_GHz = linspace(12, 18, K);
        cfg.fc = cfg.fc_GHz * 1e9;

        cfg.dynamic_safe_tau = scaled_safe_tau( ...
            safePoint, K, cfg.M_jam);

        for learnerIndex = 1:numel(suite.learners)

            learner = suite.learners(learnerIndex);
            rowIndex = rowIndex + 1;

            result = run_multi_seed_pair( ...
                cfg, learner, "contextual_expert");

            raw{rowIndex} = result;
            rows{rowIndex} = c6_summary_row( ...
                result, "K", K, cfg, safePoint);

            persist_partial( ...
                rows, rowIndex, raw, ...
                tableFolder, rawFolder, ...
                cfgBase, suite, safePoint);
        end
    end

    %% T scaling
    for T = suite.c6TGrid

        cfg = cfgBase;
        cfg.K = 12;
        cfg.T = T;
        cfg.fc_GHz = linspace(12, 18, cfg.K);
        cfg.fc = cfg.fc_GHz * 1e9;
        cfg.dynamic_safe_tau = safePoint.tau;

        for learnerIndex = 1:numel(suite.learners)

            learner = suite.learners(learnerIndex);
            rowIndex = rowIndex + 1;

            result = run_multi_seed_pair( ...
                cfg, learner, "contextual_expert");

            raw{rowIndex} = result;
            rows{rowIndex} = c6_summary_row( ...
                result, "T", T, cfg, safePoint);

            persist_partial( ...
                rows, rowIndex, raw, ...
                tableFolder, rawFolder, ...
                cfgBase, suite, safePoint);
        end
    end

    tableC6 = vertcat(rows{:});

    write_table_bundle(tableC6, fullfile( ...
        tableFolder, "Table_C6_scaling"));

    save(fullfile(rawFolder, "C6_dynamic_safe.mat"), ...
        "tableC6", "raw", "cfgBase", ...
        "suite", "safePoint", "-v7.3");

    plot_dynamic_c6_performance( ...
        tableC6, fullfile( ...
            figureFolder, ...
            "Figure_C6_performance_scaling.png"));

    plot_dynamic_c6_runtime( ...
        tableC6, fullfile( ...
            figureFolder, ...
            "Figure_C6_runtime_scaling.png"));

    outputs.outputRoot = outputRoot;
    outputs.tableC6 = tableC6;
    outputs.safePoint = safePoint;

end


function tau = scaled_safe_tau(point, K, attackBudget)

    uniformReference = attackBudget / K;

    referenceUniform = ...
        point.referenceAttackBudget / point.referenceK;

    normalizedExcess = ...
        (point.tau - referenceUniform) ...
        / max(1 - referenceUniform, realmin);

    normalizedExcess = max(normalizedExcess, 0);

    tau = uniformReference ...
        + normalizedExcess * (1 - uniformReference);

    tau = min(max(tau, uniformReference), 1);
end


function row = c6_summary_row( ...
    result, scaleType, scaleValue, cfg, safePoint)

    s = result.summary;
    learnerName = get_learner_display_name( ...
        result.learnerType);

    tau = NaN;

    if lower(string(result.learnerType)) == "dpact_safe"
        tau = cfg.dynamic_safe_tau;
        learnerName = "D-PACT-Safe95";
    end

    row = table( ...
        learnerName, ...
        string(scaleType), ...
        scaleValue, ...
        cfg.K, ...
        cfg.T, ...
        tau, ...
        s.meanGoodputMbps, ...
        s.ci95GoodputMbps, ...
        s.meanPdr, ...
        s.ci95Pdr, ...
        s.meanExpectedJamHit, ...
        s.ci95ExpectedJamHit, ...
        s.meanJamHitRate, ...
        s.ci95JamHitRate, ...
        s.meanFixedArmRegret, ...
        s.ci95FixedArmRegret, ...
        s.meanRuntime, ...
        1000 * s.meanRuntime / cfg.T, ...
        'VariableNames', { ...
            'Learner', ...
            'ScaleType', ...
            'ScaleValue', ...
            'K', ...
            'T', ...
            'Tau', ...
            'GoodputMbps', ...
            'GoodputCI95', ...
            'PDR', ...
            'PDRCI95', ...
            'ExpectedJamHit', ...
            'ExpectedJamHitCI95', ...
            'EmpiricalJamHit', ...
            'EmpiricalJamHitCI95', ...
            'FixedArmRegret', ...
            'FixedArmRegretCI95', ...
            'RuntimeSeconds', ...
            'RuntimePer1000Rounds'});
end


function persist_partial( ...
    rows, rowIndex, raw, ...
    tableFolder, rawFolder, ...
    cfgBase, suite, safePoint)

    partial = vertcat(rows{1:rowIndex});

    writetable(partial, fullfile( ...
        tableFolder, "Table_C6_partial.csv"));

    save(fullfile(rawFolder, "C6_partial.mat"), ...
        "rows", "raw", "cfgBase", ...
        "suite", "safePoint", "-v7.3");
end


function ensure_folder(pathValue)

    if ~isfolder(pathValue)
        mkdir(pathValue);
    end
end

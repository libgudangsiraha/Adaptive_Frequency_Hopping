function outputs = finalize_communication_results(mode)
%FINALIZE_COMMUNICATION_RESULTS Build the paper-ready result package.
%
% This function does not rerun experiments. It reads completed result
% MAT files, produces concise final tables, LaTeX fragments, figures,
% and a numerical claim report.

    if nargin < 1
        mode = "full";
    end

    projectRoot = setup_paths();
    mode = lower(string(mode));

    outputRoot = fullfile( ...
        projectRoot, "results", "paper_final", char(mode));

    tableFolder = fullfile(outputRoot, "tables");
    latexFolder = fullfile(outputRoot, "latex");
    figureFolder = fullfile(outputRoot, "figures");

    ensure_folder(tableFolder);
    ensure_folder(latexFolder);
    ensure_folder(figureFolder);

    probePath = fullfile( ...
        projectRoot, "results", ...
        "dynamic_model_class_probe", char(mode), ...
        "raw", "C5M_model_class_probe.mat");

    c5Path = fullfile( ...
        projectRoot, "results", ...
        "dynamic_c5", char(mode), ...
        "raw", "C5_dynamic_safe.mat");

    probeData = load_required(probePath);
    c5Data = load_required(c5Path);

    tableModel = build_model_selection_table( ...
        probeData.tableEffects);

    tableC5Main = build_c5_main_table(c5Data.tableC5);
    tableC5Claims = build_c5_claim_table(c5Data.tableC5);

    write_table_bundle(tableModel, fullfile( ...
        tableFolder, "Table_P1_model_selection"));

    write_table_bundle(tableC5Main, fullfile( ...
        tableFolder, "Table_P2_C5_main_results"));

    write_table_bundle(tableC5Claims, fullfile( ...
        tableFolder, "Table_P3_C5_key_claims"));

    write_model_latex(tableModel, fullfile( ...
        latexFolder, "Table_P1_model_selection.tex"));

    write_c5_latex(tableC5Main, fullfile( ...
        latexFolder, "Table_P2_C5_main_results.tex"));

    plot_paper_model_selection( ...
        tableModel, fullfile( ...
            figureFolder, ...
            "Figure_P1_model_selection.png"));

    plot_paper_c5_summary( ...
        c5Data.tableC5, fullfile( ...
            figureFolder, ...
            "Figure_P2_C5_summary.png"));

    safeIncluded = false;
    c6Included = false;

    safePath = fullfile( ...
        projectRoot, "results", ...
        "dynamic_safe_projection", char(mode), ...
        "raw", "S1_dynamic_safe_projection.mat");

    if isfile(safePath)
        safeData = load(safePath);

        plot_paper_safe_frontier( ...
            safeData.tableS1, ...
            safeData.tableS2, ...
            safeData.unconstrained, ...
            fullfile(figureFolder, ...
                "Figure_P3_safe_frontier.png"));

        safeIncluded = true;
    end

    c6Path = fullfile( ...
        projectRoot, "results", ...
        "dynamic_c6", char(mode), ...
        "raw", "C6_dynamic_safe.mat");

    if isfile(c6Path)
        c6Data = load(c6Path);

        tableC6 = build_c6_main_table(c6Data.tableC6);

        write_table_bundle(tableC6, fullfile( ...
            tableFolder, "Table_P4_C6_scaling"));

        write_c6_latex(tableC6, fullfile( ...
            latexFolder, "Table_P4_C6_scaling.tex"));

        plot_paper_c6_summary( ...
            c6Data.tableC6, fullfile( ...
                figureFolder, ...
                "Figure_P4_C6_scaling.png"));

        c6Included = true;
    end

    reportPath = fullfile( ...
        outputRoot, "FINAL_COMMUNICATION_RESULTS.md");

    write_final_report( ...
        reportPath, ...
        tableModel, ...
        tableC5Claims, ...
        safeIncluded, ...
        c6Included);

    outputs.outputRoot = outputRoot;
    outputs.tableModel = tableModel;
    outputs.tableC5Main = tableC5Main;
    outputs.tableC5Claims = tableC5Claims;
    outputs.safeIncluded = safeIncluded;
    outputs.c6Included = c6Included;

    fprintf("\n========================================\n");
    fprintf("Final paper package created\n");
    fprintf("========================================\n");
    fprintf("%s\n", outputRoot);

end


function tableModel = build_model_selection_table(input)

    tableModel = input;

    tableModel.LocalEffectLower95 = ...
        tableModel.LocalMinusLCGoodputMbps ...
        - tableModel.LocalMinusLCGoodputCI95;

    tableModel.DynamicEffectLower95 = ...
        tableModel.DynamicMinusLCGoodputMbps ...
        - tableModel.DynamicMinusLCGoodputCI95;

    tableModel.RecoveryPercent = NaN(height(tableModel), 1);
    tableModel.LossMitigationPercent = NaN(height(tableModel), 1);

    positive = tableModel.LocalMinusLCGoodputMbps > 0;

    tableModel.RecoveryPercent(positive) = 100 .* ...
        tableModel.DynamicMinusLCGoodputMbps(positive) ...
        ./ tableModel.LocalMinusLCGoodputMbps(positive);

    negative = tableModel.LocalMinusLCGoodputMbps < 0;

    tableModel.LossMitigationPercent(negative) = 100 .* ...
        (1 - abs(tableModel.DynamicMinusLCGoodputMbps(negative)) ...
        ./ abs(tableModel.LocalMinusLCGoodputMbps(negative)));

end


function output = build_c5_main_table(input)

    learners = [ ...
        "LC-Tsallis-INF-Online"; ...
        "Risk-aware EXP4"; ...
        "AUFH-EXP3++-1"; ...
        "D-PACT-AFH"; ...
        "D-PACT-Safe95"];

    regimes = [ ...
        "Nominal"; ...
        "Nonlinear interaction"; ...
        "Observable switching"; ...
        "White-box"; ...
        "Contaminated"; ...
        "Exogenous sweep"; ...
        "Mixed"; ...
        "Hidden Markov"];

    mask = ismember(input.Learner, learners) ...
        & ismember(input.Regime, regimes);

    variableNames = { ...
        'Learner', ...
        'Regime', ...
        'GoodputMbps', ...
        'GoodputCI95', ...
        'PDR', ...
        'PDRCI95', ...
        'EmpiricalJamHit', ...
        'EmpiricalJamHitCI95', ...
        'MasterLocalMass', ...
        'MasterLocalMassCI95'};

    output = input(mask, variableNames);

end


function output = build_c5_claim_table(input)

    definitions = [ ...
        "Observable switching", "D-PACT-AFH", ...
            "LC-Tsallis-INF-Online", "model_selection"; ...
        "White-box", "D-PACT-AFH", ...
            "LC-Tsallis-INF-Online", "hit_vs_lc"; ...
        "White-box", "D-PACT-Safe95", ...
            "D-PACT-AFH", "safe_vs_hit"; ...
        "Mixed", "D-PACT-Safe95", ...
            "Risk-aware EXP4", "safe_vs_ra"; ...
        "Hidden Markov", "D-PACT-Safe95", ...
            "Risk-aware EXP4", "safe_vs_ra"];

    rows = cell(size(definitions, 1), 1);

    for index = 1:size(definitions, 1)

        regime = definitions(index, 1);
        treatment = definitions(index, 2);
        reference = definitions(index, 3);
        claim = definitions(index, 4);

        treatmentRow = find_row(input, regime, treatment);
        referenceRow = find_row(input, regime, reference);

        goodputDifference = ...
            treatmentRow.GoodputMbps ...
            - referenceRow.GoodputMbps;

        goodputRelativePercent = 100 .* ...
            goodputDifference ...
            ./ max(referenceRow.GoodputMbps, eps);

        hitDifference = ...
            treatmentRow.EmpiricalJamHit ...
            - referenceRow.EmpiricalJamHit;

        if referenceRow.EmpiricalJamHit > 0
            hitRelativePercent = 100 .* hitDifference ...
                ./ referenceRow.EmpiricalJamHit;
        else
            hitRelativePercent = NaN;
        end

        rows{index} = table( ...
            claim, regime, treatment, reference, ...
            treatmentRow.GoodputMbps, ...
            referenceRow.GoodputMbps, ...
            goodputDifference, ...
            goodputRelativePercent, ...
            treatmentRow.EmpiricalJamHit, ...
            referenceRow.EmpiricalJamHit, ...
            hitDifference, ...
            hitRelativePercent, ...
            'VariableNames', { ...
                'Claim', ...
                'Regime', ...
                'Treatment', ...
                'Reference', ...
                'TreatmentGoodputMbps', ...
                'ReferenceGoodputMbps', ...
                'GoodputDifferenceMbps', ...
                'GoodputRelativePercent', ...
                'TreatmentJamHit', ...
                'ReferenceJamHit', ...
                'JamHitDifference', ...
                'JamHitRelativePercent'});
    end

    output = vertcat(rows{:});

end


function output = build_c6_main_table(input)

    learners = [ ...
        "LC-Tsallis-INF-Online"; ...
        "Risk-aware EXP4"; ...
        "D-PACT-AFH"; ...
        "D-PACT-Safe95"];

    mask = ismember(input.Learner, learners);

    variableNames = { ...
        'Learner', ...
        'ScaleType', ...
        'ScaleValue', ...
        'K', ...
        'T', ...
        'Tau', ...
        'GoodputMbps', ...
        'GoodputCI95', ...
        'EmpiricalJamHit', ...
        'EmpiricalJamHitCI95', ...
        'RuntimeSeconds', ...
        'RuntimePer1000Rounds'};

    output = input(mask, variableNames);

end


function row = find_row(input, regime, learner)

    match = input.Regime == regime ...
        & input.Learner == learner;

    if nnz(match) ~= 1
        error( ...
            "Expected one row for regime '%s', learner '%s'; found %d.", ...
            regime, learner, nnz(match));
    end

    row = input(match, :);

end


function data = load_required(pathValue)

    if ~isfile(pathValue)
        error("Required result file is missing: %s", pathValue);
    end

    data = load(pathValue);

end


function ensure_folder(pathValue)

    if ~isfolder(pathValue)
        mkdir(pathValue);
    end

end

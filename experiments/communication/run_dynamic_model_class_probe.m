function outputs = run_dynamic_model_class_probe(mode)
%RUN_DYNAMIC_MODEL_CLASS_PROBE Focused LC/local model-class diagnostic.
%
% Compares:
%   LC-INF;
%   D-PACT forced to LC;
%   D-PACT forced to Local;
%   dynamic D-PACT-Base.
%
% The two regimes have no active jammer, so the probe isolates
% communication model mismatch rather than prediction-risk effects.

    if nargin < 1
        mode = "quick";
    end

    projectRoot = setup_paths();
    suite = get_dynamic_c5_c6_config(mode);

    outputRoot = fullfile( ...
        projectRoot, ...
        "results", ...
        "dynamic_model_class_probe", ...
        char(lower(string(mode))));

    tableFolder = fullfile(outputRoot, "tables");
    figureFolder = fullfile(outputRoot, "figures");
    rawFolder = fullfile(outputRoot, "raw");
    checkpointFolder = fullfile(outputRoot, "checkpoints");

    ensure_folder(tableFolder);
    ensure_folder(figureFolder);
    ensure_folder(rawFolder);
    ensure_folder(checkpointFolder);

    cfgBase = get_base_config();
    cfgBase.T = suite.c5T;
    cfgBase.seedList = suite.c5Seeds;
    cfgBase.numSeeds = numel(suite.c5Seeds);
    cfgBase.M_jam = 1;
    cfgBase.detect_beta = 0;
    cfgBase.explore_nu = 0;
    cfgBase.dynamic_prediction_risk_mode = "hit_probability";

    cfgBase.resume = true;
    cfgBase.use_parallel = true;
    cfgBase.parallel_workers = 0;
    cfgBase.checkpoint_root = checkpointFolder;
    cfgBase.store_full_histories = false;
    cfgBase.store_metric_timeseries = false;

    regimeLabels = [ ...
        "Nonlinear interaction"; ...
        "Observable switching"];

    environmentRegimes = [ ...
        "nonlinear_interaction"; ...
        "observable_switching"];

    variantNames = [ ...
        "LC-INF"; ...
        "D-PACT LC-only"; ...
        "D-PACT Local-only"; ...
        "D-PACT dynamic"];

    learnerTypes = [ ...
        "lc_inf_online"; ...
        "dpact_nodetect"; ...
        "dpact_nodetect"; ...
        "dpact_nodetect"];

    forceBases = [ ...
        "none"; ...
        "lc"; ...
        "local"; ...
        "none"];

    numRows = ...
        numel(regimeLabels) * numel(variantNames);

    rows = cell(numRows, 1);
    raw = cell(numRows, 1);
    rowIndex = 0;

    for regimeIndex = 1:numel(regimeLabels)

        for variantIndex = 1:numel(variantNames)

            cfg = cfgBase;
            cfg.environment_regime = ...
                environmentRegimes(regimeIndex);

            cfg.dynamic_force_base = ...
                forceBases(variantIndex);

            result = run_multi_seed_pair( ...
                cfg, learnerTypes(variantIndex), "none");

            rowIndex = rowIndex + 1;
            raw{rowIndex} = result;

            s = result.summary;

            rows{rowIndex} = table( ...
                variantNames(variantIndex), ...
                regimeLabels(regimeIndex), ...
                s.meanGoodputMbps, ...
                s.ci95GoodputMbps, ...
                s.meanPdr, ...
                s.ci95Pdr, ...
                s.meanMasterLcMass, ...
                s.ci95MasterLcMass, ...
                s.meanMasterLocalMass, ...
                s.ci95MasterLocalMass, ...
                s.meanRuntime, ...
                'VariableNames', { ...
                    'Variant', ...
                    'Regime', ...
                    'GoodputMbps', ...
                    'GoodputCI95', ...
                    'PDR', ...
                    'PDRCI95', ...
                    'MasterLcMass', ...
                    'MasterLcMassCI95', ...
                    'MasterLocalMass', ...
                    'MasterLocalMassCI95', ...
                    'RuntimeSeconds'});
        end
    end

    tableM = vertcat(rows{:});
    tableEffects = build_probe_effects( ...
        tableM, raw, regimeLabels);

    write_table_bundle(tableM, fullfile( ...
        tableFolder, "Table_C5M_model_class_probe"));

    write_table_bundle(tableEffects, fullfile( ...
        tableFolder, "Table_C5M_model_class_effects"));

    save(fullfile(rawFolder, "C5M_model_class_probe.mat"), ...
        "tableM", "tableEffects", "raw", ...
        "cfgBase", "suite", "-v7.3");

    plot_dynamic_model_class_probe( ...
        tableM, fullfile( ...
            figureFolder, ...
            "Figure_C5M_model_class_probe.png"));

    fprintf("========================================");
    fprintf("Online model-class effects");
    fprintf("========================================");
    disp(tableEffects);

    outputs.outputRoot = outputRoot;
    outputs.tableM = tableM;
    outputs.tableEffects = tableEffects;

end


function tableEffects = build_probe_effects( ...
    tableM, raw, regimeLabels)

    rows = cell(numel(regimeLabels), 1);

    for regimeIndex = 1:numel(regimeLabels)

        regime = regimeLabels(regimeIndex);

        lcIndex = find( ...
            tableM.Regime == regime ...
            & tableM.Variant == "D-PACT LC-only", ...
            1, "first");

        localIndex = find( ...
            tableM.Regime == regime ...
            & tableM.Variant == "D-PACT Local-only", ...
            1, "first");

        dynamicIndex = find( ...
            tableM.Regime == regime ...
            & tableM.Variant == "D-PACT dynamic", ...
            1, "first");

        lc = raw{lcIndex};
        local = raw{localIndex};
        dynamic = raw{dynamicIndex};

        [localEffect, localCI] = mean_ci( ...
            local.avgGoodputMbps - lc.avgGoodputMbps);

        [dynamicEffect, dynamicCI] = mean_ci( ...
            dynamic.avgGoodputMbps - lc.avgGoodputMbps);

        rows{regimeIndex} = table( ...
            regime, ...
            localEffect, ...
            localCI, ...
            dynamicEffect, ...
            dynamicCI, ...
            tableM.MasterLocalMass(dynamicIndex), ...
            tableM.MasterLocalMassCI95(dynamicIndex), ...
            'VariableNames', { ...
                'Regime', ...
                'LocalMinusLCGoodputMbps', ...
                'LocalMinusLCGoodputCI95', ...
                'DynamicMinusLCGoodputMbps', ...
                'DynamicMinusLCGoodputCI95', ...
                'DynamicLocalMass', ...
                'DynamicLocalMassCI95'});
    end

    tableEffects = vertcat(rows{:});

end


function [meanValue, ci95] = mean_ci(values)

    values = values(:);
    values = values(isfinite(values));

    meanValue = mean(values);

    if numel(values) <= 1
        ci95 = NaN;
    else
        ci95 = 1.96 * std(values) / sqrt(numel(values));
    end

end


function ensure_folder(pathValue)

    if ~isfolder(pathValue)
        mkdir(pathValue);
    end
end

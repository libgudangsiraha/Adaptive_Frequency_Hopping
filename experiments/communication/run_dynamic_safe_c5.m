function outputs = run_dynamic_safe_c5(mode)
%RUN_DYNAMIC_SAFE_C5 Environment-regime robustness.

    if nargin < 1
        mode = "quick";
    end

    projectRoot = setup_paths();
    suite = get_dynamic_c5_c6_config(mode);
    safePoint = resolve_dynamic_safe_operating_point( ...
        projectRoot, suite.safeLabel);

    outputRoot = fullfile(projectRoot, suite.c5OutputRoot);
    tableFolder = fullfile(outputRoot, "tables");
    figureFolder = fullfile(outputRoot, "figures");
    rawFolder = fullfile(outputRoot, "raw");
    checkpointFolder = fullfile(outputRoot, "checkpoints");

    ensure_folder(tableFolder);
    ensure_folder(figureFolder);
    ensure_folder(rawFolder);
    ensure_folder(checkpointFolder);

    cfgBase = get_base_config();
    cfgBase.T = suite.c5T;
    cfgBase.seedList = suite.c5Seeds;
    cfgBase.numSeeds = numel(suite.c5Seeds);

    cfgBase.M_jam = suite.attackBudget;
    cfgBase.sweep_width = suite.attackBudget;
    cfgBase.detect_beta = suite.beta;
    cfgBase.explore_nu = suite.nu;
    cfgBase.dynamic_prediction_risk_mode = ...
        "hit_probability";
    cfgBase.dynamic_safe_tau = safePoint.tau;

    cfgBase.resume = true;
    cfgBase.use_parallel = true;
    cfgBase.parallel_workers = 0;
    cfgBase.checkpoint_root = checkpointFolder;
    cfgBase.store_full_histories = false;
    cfgBase.store_metric_timeseries = false;

    numRows = ...
        numel(suite.c5RegimeLabels) ...
        * numel(suite.learners);

    rows = cell(numRows, 1);
    raw = cell(numRows, 1);
    rowIndex = 0;

    for regimeIndex = 1:numel(suite.c5RegimeLabels)

        regimeLabel = suite.c5RegimeLabels(regimeIndex);
        environmentRegime = ...
            suite.c5EnvironmentRegimes(regimeIndex);
        adversary = suite.c5Adversaries(regimeIndex);

        cfg = cfgBase;
        cfg.environment_regime = environmentRegime;

        for learnerIndex = 1:numel(suite.learners)

            learner = suite.learners(learnerIndex);
            rowIndex = rowIndex + 1;

            fprintf("\n===== C5 | %s | %s =====\n", ...
                regimeLabel, ...
                get_learner_display_name(learner));

            result = run_multi_seed_pair( ...
                cfg, learner, adversary);

            raw{rowIndex} = result;
            rows{rowIndex} = c5_summary_row( ...
                result, regimeLabel, safePoint, cfg);

            partial = vertcat(rows{1:rowIndex});
            writetable(partial, fullfile( ...
                tableFolder, "Table_C5_partial.csv"));

            save(fullfile(rawFolder, "C5_partial.mat"), ...
                "rows", "raw", "cfgBase", "suite", ...
                "safePoint", "-v7.3");
        end
    end

    tableC5 = vertcat(rows{:});
    tableEffects = c5_paired_effects( ...
        tableC5, raw, suite);

    write_table_bundle(tableC5, fullfile( ...
        tableFolder, "Table_C5_regime_robustness"));

    write_table_bundle(tableEffects, fullfile( ...
        tableFolder, "Table_C5_paired_effects"));

    masterMask = startsWith( ...
        tableC5.Learner, "D-PACT");

    masterVariables = { ...
        'Learner', ...
        'Regime', ...
        'GoodputMbps', ...
        'GoodputCI95', ...
        'MasterLcMass', ...
        'MasterLcMassCI95', ...
        'MasterLocalMass', ...
        'MasterLocalMassCI95', ...
        'MasterEffectiveCount', ...
        'MasterEffectiveCountCI95'};

    tableMaster = tableC5(masterMask, masterVariables);

    write_table_bundle(tableMaster, fullfile( ...
        tableFolder, "Table_C5_master_allocation"));

    save(fullfile(rawFolder, "C5_dynamic_safe.mat"), ...
        "tableC5", "tableEffects", "tableMaster", "raw", ...
        "cfgBase", "suite", "safePoint", "-v7.3");

    plot_dynamic_c5_heatmaps( ...
        tableC5, fullfile( ...
            figureFolder, ...
            "Figure_C5_regime_heatmaps.png"));

    plot_dynamic_c5_master_allocation( ...
        tableMaster, fullfile( ...
            figureFolder, ...
            "Figure_C5_master_allocation.png"));

    outputs.outputRoot = outputRoot;
    outputs.tableC5 = tableC5;
    outputs.tableEffects = tableEffects;
    outputs.tableMaster = tableMaster;
    outputs.safePoint = safePoint;

end


function row = c5_summary_row( ...
    result, regimeLabel, safePoint, cfg)

    s = result.summary;
    learnerName = get_learner_display_name( ...
        result.learnerType);

    tau = NaN;

    if lower(string(result.learnerType)) == "dpact_safe"
        tau = cfg.dynamic_safe_tau;
        learnerName = "D-PACT-Safe95";
    end

    row = table( ...
        learnerName, ...
        string(regimeLabel), ...
        get_adversary_display_name(result.adversaryType), ...
        string(result.environmentRegime), ...
        tau, ...
        s.meanGoodputMbps, ...
        s.ci95GoodputMbps, ...
        s.meanPdr, ...
        s.ci95Pdr, ...
        s.meanMeanSinrDb, ...
        s.ci95MeanSinrDb, ...
        s.meanExpectedJamHit, ...
        s.ci95ExpectedJamHit, ...
        s.meanJamHitRate, ...
        s.ci95JamHitRate, ...
        s.meanSwitchingRate, ...
        s.ci95SwitchingRate, ...
        s.meanMasterLcMass, ...
        s.ci95MasterLcMass, ...
        s.meanMasterLocalMass, ...
        s.ci95MasterLocalMass, ...
        s.meanMasterEffectiveCount, ...
        s.ci95MasterEffectiveCount, ...
        s.meanRuntime, ...
        'VariableNames', { ...
            'Learner', ...
            'Regime', ...
            'Adversary', ...
            'EnvironmentRegime', ...
            'Tau', ...
            'GoodputMbps', ...
            'GoodputCI95', ...
            'PDR', ...
            'PDRCI95', ...
            'MeanSINRdB', ...
            'MeanSINRdBCI95', ...
            'ExpectedJamHit', ...
            'ExpectedJamHitCI95', ...
            'EmpiricalJamHit', ...
            'EmpiricalJamHitCI95', ...
            'SwitchingRate', ...
            'SwitchingRateCI95', ...
            'MasterLcMass', ...
            'MasterLcMassCI95', ...
            'MasterLocalMass', ...
            'MasterLocalMassCI95', ...
            'MasterEffectiveCount', ...
            'MasterEffectiveCountCI95', ...
            'RuntimeSeconds'});
end


function tableEffects = c5_paired_effects( ...
    tableC5, raw, suite)

    comparisons = [ ...
        "D-PACT-AFH", "LC-Tsallis-INF-Online"; ...
        "D-PACT-Safe95", "D-PACT-AFH"; ...
        "D-PACT-Safe95", "Risk-aware EXP4"; ...
        "D-PACT-Safe95", "AUFH-EXP3++-1"];

    rows = cell( ...
        numel(suite.c5RegimeLabels) ...
        * size(comparisons, 1), 1);

    rowIndex = 0;

    for regimeIndex = 1:numel(suite.c5RegimeLabels)

        regime = suite.c5RegimeLabels(regimeIndex);

        for comparisonIndex = 1:size(comparisons, 1)

            treatmentName = comparisons(comparisonIndex, 1);
            referenceName = comparisons(comparisonIndex, 2);

            treatmentIndex = find( ...
                tableC5.Regime == regime ...
                & tableC5.Learner == treatmentName, ...
                1, "first");

            referenceIndex = find( ...
                tableC5.Regime == regime ...
                & tableC5.Learner == referenceName, ...
                1, "first");

            treatment = raw{treatmentIndex};
            reference = raw{referenceIndex};

            [goodputEffect, goodputCI] = mean_ci( ...
                treatment.avgGoodputMbps ...
                - reference.avgGoodputMbps);

            [pdrEffect, pdrCI] = mean_ci( ...
                treatment.pdr - reference.pdr);

            [hitEffect, hitCI] = mean_ci( ...
                treatment.jamHitRate ...
                - reference.jamHitRate);

            rowIndex = rowIndex + 1;

            rows{rowIndex} = table( ...
                regime, ...
                treatmentName, ...
                referenceName, ...
                goodputEffect, ...
                goodputCI, ...
                pdrEffect, ...
                pdrCI, ...
                hitEffect, ...
                hitCI, ...
                'VariableNames', { ...
                    'Regime', ...
                    'Treatment', ...
                    'Reference', ...
                    'GoodputEffect', ...
                    'GoodputEffectCI95', ...
                    'PDREffect', ...
                    'PDREffectCI95', ...
                    'EmpiricalJamHitEffect', ...
                    'EmpiricalJamHitEffectCI95'});
        end
    end

    tableEffects = vertcat(rows{:});
end


function [meanValue, ci95] = mean_ci(values)

    values = values(:);
    values = values(isfinite(values));
    meanValue = mean(values);

    if numel(values) <= 1
        ci95 = NaN;
    else
        ci95 = 1.96 * std(values) / sqrt(numel(values));
    end
end


function ensure_folder(pathValue)

    if ~isfolder(pathValue)
        mkdir(pathValue);
    end
end
